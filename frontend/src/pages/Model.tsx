import { Info } from "lucide-react";
import { useMemo, useState } from "react";
import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  LabelList,
  Line,
  LineChart,
  ReferenceLine,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";
import { useModelReport } from "../api/hooks";
import type { ModelReport } from "../api/types";
import { ChartTooltip, Legend } from "../components/charts";
import { LearningLoop } from "../components/LearningLoop";
import { Card, CardTitle, ErrorBox, Loading, PageTitle, Segmented } from "../components/ui";
import { num, pct } from "../lib/format";
import { C, axisProps, goldRamp } from "../lib/tokens";

const TICKS = [0, 0.25, 0.5, 0.75, 1];

type MetricKey = "f1" | "pr_auc" | "recall" | "precision" | "roc_auc";

export default function Model() {
  const { data, isLoading, error, refetch } = useModelReport();
  if (isLoading) return <Loading />;
  if (error || !data) return <ErrorBox error={error} onRetry={refetch} />;
  return (
    <>
      <PageTitle
        title="Model insights"
        sup={data.model_version}
        sub={`Hybrid detector = ${data.weights.ml} × Random Forest + ${data.weights.rules} × rule engine + ${data.weights.anomaly} × Isolation Forest. Evaluated on a held-out split and on a harder, distribution-shifted test set.`}
      />
      <Headline r={data} />
      <LearningLoop />
      <div className="mt-5 grid gap-5 xl:grid-cols-2">
        <Ablation r={data} />
        <ThresholdExplorer r={data} />
        <Curves r={data} />
        <PerType r={data} />
        <Confusion r={data} />
        <Importance r={data} />
      </div>
      <Card className="mt-5">
        <CardTitle
          title="Dataset"
          sub="Synthetic agricultural supply-chain transactions generated by the project's simulator"
        />
        <div className="grid gap-5 lg:grid-cols-3">
          <div className="space-y-2 text-sm text-ink-2">
            <p>
              <b className="text-ink">{num(data.dataset.rows)}</b> transactions (
              {num(data.dataset.train_rows)} train / {num(data.dataset.test_rows)} test) +{" "}
              <b className="text-ink">{num(data.dataset.shifted_rows)}</b> shifted-test rows.
            </p>
            <p>Fraud rate: {pct(data.dataset.fraud_rate, 1)}. 21 engineered features per transaction.</p>
            <p className="text-xs text-muted">Trained {new Date(data.trained_at).toLocaleString("en-IN")}</p>
          </div>
          <div className="lg:col-span-2">
            <div className="flex flex-wrap gap-2">
              {Object.entries(data.dataset.class_counts).map(([k, v]) => (
                <span key={k} className="card-inner px-3 py-2 text-xs">
                  <span className="text-muted">{k.replace(/_/g, " ")}</span>{" "}
                  <b className="tnum ml-1 text-ink">{num(v)}</b>
                </span>
              ))}
            </div>
            <p className="mt-4 flex gap-2 rounded-2xl border border-gold/30 bg-gold/5 p-3 text-xs text-ink-2">
              <Info size={15} className="mt-0.5 shrink-0 text-gold" />
              Honest caveat: the data is synthetic, so absolute scores are optimistic. To keep it realistic
              the simulator adds overlapping distributions, ~4% legitimate outliers (drought price spikes,
              bumper harvests, honestly disclosed temperature breaches) and 0.4% label noise, and we report a
              separate shifted test set where fraud is subtler.
            </p>
          </div>
        </div>
      </Card>
    </>
  );
}

function Headline({ r }: { r: ModelReport }) {
  const items: { k: MetricKey; label: string }[] = [
    { k: "pr_auc", label: "PR-AUC" },
    { k: "roc_auc", label: "ROC-AUC" },
    { k: "precision", label: "Precision" },
    { k: "recall", label: "Recall" },
    { k: "f1", label: "F1 score" },
  ];
  return (
    <div className="grid grid-cols-2 gap-5 md:grid-cols-5">
      {items.map((i) => (
        <div key={i.k} className="card p-4">
          <p className="text-[11px] text-muted">{i.label}</p>
          <p className="tnum mt-2 text-3xl font-light text-ink">{r.headline[i.k].toFixed(3)}</p>
          <p className="tnum mt-1 text-[11px] text-muted">
            shifted set <span className="text-ink-2">{r.headline.shifted[i.k].toFixed(3)}</span>
          </p>
        </div>
      ))}
    </div>
  );
}

function Ablation({ r }: { r: ModelReport }) {
  const [metric, setMetric] = useState<MetricKey>("f1");
  const [set, setSet] = useState<"test" | "shifted">("test");
  const rows = (set === "test" ? r.ablation : r.ablation_shifted).map((a) => ({
    model: a.model,
    v: a[metric],
  }));
  return (
    <Card>
      <CardTitle
        title="Ablation: is the hybrid worth it?"
        sub="Each component alone vs. the combined detector"
        right={
          <Segmented
            value={set}
            onChange={setSet}
            options={[
              { value: "test", label: "Held-out" },
              { value: "shifted", label: "Shifted" },
            ]}
          />
        }
      />
      <div className="mb-3">
        <Segmented
          value={metric}
          onChange={setMetric}
          options={[
            { value: "f1", label: "F1" },
            { value: "pr_auc", label: "PR-AUC" },
            { value: "precision", label: "Precision" },
            { value: "recall", label: "Recall" },
          ]}
        />
      </div>
      <div className="h-56">
        <ResponsiveContainer>
          <BarChart data={rows} layout="vertical" margin={{ left: 0, right: 40 }}>
            <XAxis type="number" domain={[0, 1]} hide />
            <YAxis type="category" dataKey="model" {...axisProps} axisLine={false} width={170} />
            <Tooltip
              cursor={{ fill: "rgba(255,255,255,0.03)" }}
              content={<ChartTooltip valueFormatter={(v) => Number(v).toFixed(3)} />}
            />
            <Bar dataKey="v" name={metric.toUpperCase()} radius={[0, 4, 4, 0]} barSize={16}>
              {rows.map((x) => (
                <Cell key={x.model} fill={x.model.startsWith("Hybrid") ? C.gold : "#5b5a55"} />
              ))}
              <LabelList
                dataKey="v"
                position="right"
                fill={C.ink2}
                fontSize={11}
                formatter={(v) => Number(v).toFixed(3)}
              />
            </Bar>
          </BarChart>
        </ResponsiveContainer>
      </div>
      <p className="text-[11px] text-muted">
        The Isolation Forest is weak alone (it only knows "unusual", not "fraud") but adds a safety net for
        patterns the classifier never saw.
      </p>
    </Card>
  );
}

function ThresholdExplorer({ r }: { r: ModelReport }) {
  const [t, setT] = useState(r.thresholds.flag);
  const row = useMemo(
    () =>
      r.threshold_sweep.reduce((best, x) =>
        Math.abs(x.threshold - t) < Math.abs(best.threshold - t) ? x : best,
      ),
    [r, t],
  );
  const hist = r.score_hist.map((h) => ({ ...h, label: h.bin.toFixed(2) }));
  return (
    <Card>
      <CardTitle
        title="Threshold explorer"
        sub="Drag to see the precision / recall trade-off on the test set"
      />
      <div className="flex items-center gap-4">
        <input
          type="range"
          min={0.05}
          max={0.95}
          step={0.05}
          value={t}
          onChange={(e) => setT(Number(e.target.value))}
          className="!border-0 !bg-transparent !p-0 accent-[#e8c15a]"
          aria-label="Decision threshold"
        />
        <span className="tnum w-14 text-right font-mono text-lg text-gold">{row.threshold.toFixed(2)}</span>
      </div>
      <div className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-4">
        <MiniStat k="Precision" v={pct(row.precision, 1)} />
        <MiniStat k="Recall" v={pct(row.recall, 1)} />
        <MiniStat k="Fraud missed" v={String(row.fn)} />
        <MiniStat k="False alarms" v={String(row.fp)} />
      </div>
      <div className="mt-4 grid grid-cols-2 gap-3">
        <HistMini data={hist} dataKey="legit" title="Legitimate tx" color="#6b6a64" t={row.threshold} />
        <HistMini data={hist} dataKey="fraud" title="Fraudulent tx" color={C.gold} t={row.threshold} />
      </div>
      <p className="mt-2 text-[11px] text-muted">
        Risk-score distributions (separate scales). Everything right of the dashed line gets flagged.
        Production thresholds: flag ≥ {r.thresholds.flag}, quarantine ≥ {r.thresholds.quarantine}.
      </p>
    </Card>
  );
}

function HistMini({
  data,
  dataKey,
  title,
  color,
  t,
}: {
  data: object[];
  dataKey: string;
  title: string;
  color: string;
  t: number;
}) {
  return (
    <div>
      <p className="mb-1 text-[11px] text-muted">{title}</p>
      <div className="h-28">
        <ResponsiveContainer>
          <BarChart data={data} margin={{ left: -28, right: 4, top: 4 }} barCategoryGap={1}>
            <XAxis dataKey="label" {...axisProps} interval={4} />
            <YAxis {...axisProps} allowDecimals={false} />
            <Tooltip
              cursor={{ fill: "rgba(255,255,255,0.03)" }}
              content={<ChartTooltip labelFormatter={(l) => `Risk ${l}–${(Number(l) + 0.05).toFixed(2)}`} />}
            />
            <ReferenceLine x={t.toFixed(2)} stroke={C.ink2} strokeDasharray="4 3" />
            <Bar dataKey={dataKey} name="Count" fill={color} radius={[2, 2, 0, 0]} />
          </BarChart>
        </ResponsiveContainer>
      </div>
    </div>
  );
}

function MiniStat({ k, v }: { k: string; v: string }) {
  return (
    <div className="card-inner px-3 py-2">
      <p className="text-[10px] uppercase tracking-wider text-muted">{k}</p>
      <p className="tnum mt-0.5 text-lg text-ink">{v}</p>
    </div>
  );
}

function Curves({ r }: { r: ModelReport }) {
  const [which, setWhich] = useState<"roc" | "pr">("roc");
  const roc = r.roc.hybrid.map((p) => ({ x: p.x, hybrid: p.y }));
  const rules = r.roc.rules.map((p) => ({ x: p.x, rules: p.y }));
  const merged = [...roc, ...rules].sort((a, b) => a.x - b.x);
  const pr = r.pr.map((p) => ({ x: p.x, precision: p.y }));
  return (
    <Card>
      <CardTitle
        title={which === "roc" ? "ROC curve" : "Precision–recall curve"}
        sub={
          which === "roc"
            ? "True-positive rate vs false-positive rate"
            : "Precision vs recall for the hybrid score"
        }
        right={
          <Segmented
            value={which}
            onChange={setWhich}
            options={[
              { value: "roc", label: "ROC" },
              { value: "pr", label: "PR" },
            ]}
          />
        }
      />
      {which === "roc" && (
        <div className="mb-2">
          <Legend
            items={[
              { label: `Hybrid (AUC ${r.headline.roc_auc.toFixed(3)})`, color: C.gold },
              { label: `Rules only (AUC ${r.ablation[0].roc_auc.toFixed(3)})`, color: "#8a8983" },
            ]}
          />
        </div>
      )}
      <div className="h-60">
        <ResponsiveContainer>
          {which === "roc" ? (
            <LineChart data={merged} margin={{ left: -18, right: 8, top: 6 }}>
              <CartesianGrid stroke={C.grid} />
              <XAxis dataKey="x" type="number" domain={[0, 1]} ticks={TICKS} {...axisProps} />
              <YAxis domain={[0, 1]} ticks={TICKS} {...axisProps} />
              <ReferenceLine
                segment={[
                  { x: 0, y: 0 },
                  { x: 1, y: 1 },
                ]}
                stroke={C.line}
                strokeDasharray="4 4"
              />
              <Tooltip
                content={
                  <ChartTooltip
                    labelFormatter={(l) => `FPR ${Number(l).toFixed(3)}`}
                    valueFormatter={(v) => Number(v).toFixed(3)}
                  />
                }
              />
              <Line
                dataKey="rules"
                name="Rules only"
                stroke="#8a8983"
                strokeWidth={2}
                dot={false}
                connectNulls
                type="stepAfter"
              />
              <Line
                dataKey="hybrid"
                name="Hybrid"
                stroke={C.gold}
                strokeWidth={2}
                dot={false}
                connectNulls
                type="stepAfter"
              />
            </LineChart>
          ) : (
            <LineChart data={pr} margin={{ left: -18, right: 8, top: 6 }}>
              <CartesianGrid stroke={C.grid} />
              <XAxis dataKey="x" type="number" domain={[0, 1]} ticks={TICKS} {...axisProps} />
              <YAxis domain={[0, 1]} ticks={TICKS} {...axisProps} />
              <Tooltip
                content={
                  <ChartTooltip
                    labelFormatter={(l) => `Recall ${Number(l).toFixed(3)}`}
                    valueFormatter={(v) => Number(v).toFixed(3)}
                  />
                }
              />
              <Line
                dataKey="precision"
                name="Precision"
                stroke={C.gold}
                strokeWidth={2}
                dot={false}
                type="stepAfter"
              />
            </LineChart>
          )}
        </ResponsiveContainer>
      </div>
    </Card>
  );
}

