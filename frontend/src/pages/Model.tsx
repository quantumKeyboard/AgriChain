const SHORT: Record<string, string> = {
  none: "Legit",
  price_manipulation: "Price",
  phantom_quantity: "Phantom",
  organic_label_fraud: "Organic",
  cold_chain_concealed: "Cold chain",
  circular_trading: "Circular",
  duplicate_invoice: "Duplicate",
};

function Confusion({ r }: { r: ModelReport }) {
  const { display, matrix, labels } = r.confusion_matrix;
  const rowMax = matrix.map((row) => Math.max(...row, 1));
  return (
    <Card>
      <CardTitle
        title="Confusion matrix"
        sub="Rows = true class · columns = predicted (hybrid decision + type guess) · shading = share of the row"
      />
      <div className="scroll-thin overflow-x-auto">
        <table className="border-separate text-[10px]" style={{ borderSpacing: 2 }}>
          <thead>
            <tr>
              <th />
              {labels.map((l, j) => (
                <th
                  key={l}
                  title={display[j]}
                  className="w-14 pb-1 text-center align-bottom font-medium text-muted"
                >
                  {SHORT[l] ?? l}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {matrix.map((row, i) => (
              <tr key={i}>
                <th className="pr-2 text-right font-medium whitespace-nowrap text-muted">{display[i]}</th>
                {row.map((v, j) => {
                  const share = v / rowMax[i];
                  return (
                    <td
                      key={j}
                      title={`true ${display[i]} → predicted ${display[j]}: ${v}`}
                      className="tnum h-9 w-14 rounded-md text-center font-semibold"
                      style={{
                        background: v ? goldRamp(share) : C.panel2,
                        color: share > 0.55 ? "#1a1404" : C.ink2,
                        outline: i === j ? `1px solid ${C.gold}55` : undefined,
                      }}
                    >
                      {v || ""}
                    </td>
                  );
                })}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </Card>
  );
}

